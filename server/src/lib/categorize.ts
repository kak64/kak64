import type { Department } from '../types.js';

/** מילון מילות-מפתח בעברית -> מחלקת סופר (זהה ללוגיקת הלקוח) */
const KEYWORD_MAP: Record<Department, string[]> = {
  'מוצרי חלב': ['חלב', 'גבינה', 'קוטג', 'יוגורט', 'שמנת', 'חמאה', 'לבן', 'מעדן', 'אשל', 'תנובה'],
  'ירקות ופירות': [
    'עגבני', 'מלפפון', 'חסה', 'בצל', 'שום', 'תפוח', 'בננה', 'גזר', 'תפוז', 'לימון', 'אבוקדו',
    'פלפל', 'בטטה', 'קישוא', 'חציל', 'ענב', 'אבטיח', 'מלון', 'סלק', 'כרוב', 'ברוקולי', 'ירק', 'פרי',
  ],
  'בשר ודגים': ['בשר', 'עוף', 'הודו', 'דג', 'סלמון', 'טונה', 'שניצל', 'קציצ', 'נקני', 'המבורגר', 'כבד'],
  'מאפים ולחם': ['לחם', 'פיתה', 'לחמני', 'בגט', 'חלה', 'עוג', 'קרואסון', 'מאפה', 'בורק', 'טורטיה'],
  'שימורים ויבשים': [
    'אורז', 'פסטה', 'אטריות', 'קוסקוס', 'שעועית', 'עדש', 'חומוס', 'טחינה', 'שמן', 'מלח', 'סוכר',
    'קמח', 'תירס', 'רסק', 'שימור', 'דגן', 'קפה', 'תה',
  ],
  'קפואים': ['קפוא', 'גלידה', 'מלאווח', 'בצק עלים'],
  'משקאות': ['מים', 'מיץ', 'קולה', 'סודה', 'משקה', 'בירה', 'יין', 'שתיה', 'ספרייט', 'פחית'],
  'ניקיון וטואלטיקה': [
    'ניקוי', 'סבון', 'שמפו', 'אקונומיקה', 'נייר טואלט', 'מגבונים', 'כביסה', 'מרכך', 'משחת שיניים', 'דאודורנט',
  ],
  'חטיפים ומתוקים': ['שוקולד', 'חטיף', 'במבה', 'ביסלי', 'עוגיות', 'סוכריות', 'ופל', 'מסטיק'],
  'כללי': [],
};

export function categorize(rawName: string): Department {
  const name = rawName.trim().toLowerCase();
  for (const dept of Object.keys(KEYWORD_MAP) as Department[]) {
    if (KEYWORD_MAP[dept].some((kw) => name.includes(kw.toLowerCase()))) return dept;
  }
  return 'כללי';
}
