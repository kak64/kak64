/** ממיין שם מוצר חופשי בעברית למחלקת סופר */
export function categorize(rawName: string): Department {
  const name = rawName.trim().toLowerCase();
  for (const dept of Object.keys(KEYWORD_MAP) as Department[]) {
    if (KEYWORD_MAP[dept].some((kw) => name.includes(kw.toLowerCase()))) {
      return dept;
    }
  }
  return 'כללי';
}
